def get_language(value):
    """Return a supported locale, defaulting to Uzbek Latin."""
    supported = {code for code, _ in LANGUAGES}
    return value if value in supported else DEFAULT_LANGUAGE


def translate(key, language=DEFAULT_LANGUAGE):
    """Look up one explicitly translated UI key."""
    if key not in _TEXT:
        raise KeyError(f'Unknown UI translation key: {key}')
    locale = get_language(language)
    return _TEXT[key][0 if locale == 'uz-Latn' else 1]


